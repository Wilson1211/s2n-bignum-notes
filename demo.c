#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include "s2n-bignum.h"

int main(void) {
  /* 1. 4-word (256-bit) 大數相乘 */
  uint64_t a[4] = {0xffffffffffffffffULL, ~0ULL, ~0ULL, ~0ULL};  /* 2^256 - 1 */
  uint64_t b[4] = {3, 0, 0, 0};
  uint64_t r[8];
  bignum_mul(8, r, 4, a, 4, b);
  printf("(2^256-1)*3 = ");
  for (int i = 7; i >= 0; i--) printf("%016lx", r[i]);
  printf("\n");

  /* 2. X25519：RFC 7748 的測試向量 */
  uint8_t scalar[32] = {
    0xa5,0x46,0xe3,0x6b,0xf0,0x52,0x7c,0x9d,0x3b,0x16,0x15,0x4b,0x82,0x46,0x5e,0xdd,
    0x62,0x14,0x4c,0x0a,0xc1,0xfc,0x5a,0x18,0x50,0x6a,0x22,0x44,0xba,0x44,0x9a,0xc4};
  uint8_t point[32] = {
    0xe6,0xdb,0x68,0x67,0x58,0x30,0x30,0xdb,0x35,0x94,0xc1,0xa4,0x24,0xb1,0x5f,0x7c,
    0x72,0x66,0x24,0xec,0x26,0xb3,0x35,0x3b,0x10,0xa9,0x03,0xa6,0xd0,0xab,0x1c,0x4c};
  uint8_t out[32];
  const uint8_t expect[32] = {
    0xc3,0xda,0x55,0x37,0x9d,0xe9,0xc6,0x90,0x8e,0x94,0xea,0x4d,0xf2,0x8d,0x08,0x4f,
    0x32,0xec,0xcf,0x03,0x49,0x1c,0x71,0xf7,0x54,0xb4,0x07,0x55,0x77,0xa2,0x85,0x52};
  curve25519_x25519_byte(out, scalar, point);
  printf("X25519    = ");
  for (int i = 0; i < 32; i++) printf("%02x", out[i]);
  printf("  -> %s\n", memcmp(out, expect, 32) == 0 ? "符合 RFC 7748 ✓" : "不符 ✗");
  return 0;
}
